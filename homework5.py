dictionary = {
    "Андрій": "дитина",
    "Олександр": "літній вік",
    "Максим": "дорослий",
    "Іван": "дорослий",
    "Ярослав": "підліток"
}

name = input("Введіть ім'я користувача: ")
if name in dictionary:
    print(f"Вікова група користувача з ім'ям {name}: {dictionary[name]}")
else:
    print(f"Користувача з таким ім'ям {name} не знайдено")